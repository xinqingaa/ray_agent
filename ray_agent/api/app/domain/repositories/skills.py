"""短事务 skill 仓储；外部下载和文件校验不在事务中进行。"""
from typing import Protocol


class SkillTransaction(Protocol):
    async def lock(self): ...
    async def get(self, table: str, key: str): ...
    async def all(self, table: str): ...
    async def put(self, table: str, key: str, value: dict): ...
    async def delete(self, table: str, key: str): ...
    async def bindings(self, run_id: str): ...
    async def bind(self, run_id: str, name: str, version: str, data: dict): ...
    async def references(self) -> set[str]: ...


class SkillRepository(Protocol):
    def transaction(self, run_id: str | None = None): ...
